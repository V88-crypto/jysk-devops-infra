const PATTERNS: [RegExp, string][] = [
  [/^Вариант с SKU (.+) уже существует$/, 'Варіант з артикулом $1 вже існує'],
  [/^Поле (.+) нельзя очистить$/, 'Поле $1 не можна очистити'],
  [/^Файл больше (\d+) МБ$/, 'Файл більший за $1 МБ'],
]

export const translateApiMessage = (message: string) => {
  if (MESSAGES[message]) {
    return MESSAGES[message]
  }

  const pattern = PATTERNS.find(([regex]) => regex.test(message))

  return pattern ? message.replace(pattern[0], pattern[1]) : message
}
